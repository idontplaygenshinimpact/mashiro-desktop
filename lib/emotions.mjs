/** 随机取一句 */
export function pick(arr) {
  if (!arr?.length) return "";
  return arr[Math.floor(Math.random() * arr.length)];
}

/** 格式化占位符 {n} */
export function format(text, vars = {}) {
  return String(text).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}
